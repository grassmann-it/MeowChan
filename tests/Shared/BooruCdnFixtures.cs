/// <summary>One scripted CDN answer. Build them with <see cref="BooruCdn"/>; every field is plain data.</summary>
internal sealed record BooruCdnResponse
{
    internal HttpStatusCode Status { get; init; } = HttpStatusCode.OK;
    internal byte[] Body { get; init; } = Array.Empty<byte>();
    internal string? ContentType { get; init; }
    /// <summary>When set, the body is this many generated bytes (PNG signature, then zeros) instead of <see cref="Body"/>.</summary>
    internal long? GeneratedLength { get; init; }
    /// <summary>False leaves out Content-Length (a chunked answer) for a generated body.</summary>
    internal bool DeclareLength { get; init; } = true;
    internal IReadOnlyDictionary<string, string> Headers { get; init; } = new Dictionary<string, string>();
    /// <summary>The address the transport claims to have answered from, as an HttpClient does after following a redirect.</summary>
    internal Uri? AnsweredFrom { get; init; }
    /// <summary>The answer waits for this gate (honouring cancellation) before it is returned.</summary>
    internal TaskCompletionSource? Gate { get; init; }
}

/// <summary>Factories for the CDN cases of the plan (preview and sample alike).</summary>
internal static class BooruCdn
{
    internal static BooruCdnResponse Image(byte[] body, string contentType) => new() { Body = body, ContentType = contentType };
    internal static BooruCdnResponse Png() => Image(BooruTinyImages.Png(), "image/png");
    internal static BooruCdnResponse Jpeg() => Image(BooruTinyImages.Jpeg(), "image/jpeg");
    internal static BooruCdnResponse WebP() => Image(BooruTinyImages.WebP(), "image/webp");
    internal static BooruCdnResponse Gif() => Image(BooruTinyImages.Gif(), "image/gif");

    /// <summary>A bare status without a body: 404 (missing file), 410 (gone), 403, 500.</summary>
    internal static BooruCdnResponse Status(HttpStatusCode status) => new() { Status = status };

    /// <summary><c>Retry-After: 120</c> (delta seconds) when given, no header when null.</summary>
    internal static BooruCdnResponse RateLimited(int? retryAfterSeconds = 120) =>
        Throttled(HttpStatusCode.TooManyRequests, retryAfterSeconds?.ToString(CultureInfo.InvariantCulture));

    /// <summary><c>Retry-After</c> as an HTTP date, the second form the header allows.</summary>
    internal static BooruCdnResponse RateLimitedUntil(DateTimeOffset retryAt) =>
        Throttled(HttpStatusCode.TooManyRequests, retryAt.UtcDateTime.ToString("R", CultureInfo.InvariantCulture));

    internal static BooruCdnResponse ServiceUnavailable(int? retryAfterSeconds = 30) =>
        Throttled(HttpStatusCode.ServiceUnavailable, retryAfterSeconds?.ToString(CultureInfo.InvariantCulture));

    internal static BooruCdnResponse ServiceUnavailableUntil(DateTimeOffset retryAt) =>
        Throttled(HttpStatusCode.ServiceUnavailable, retryAt.UtcDateTime.ToString("R", CultureInfo.InvariantCulture));

    /// <summary>A throttling answer whose header is not a number or date ("soon"): the host must fall back to its floor.</summary>
    internal static BooruCdnResponse ThrottledWithInvalidRetryAfter(HttpStatusCode status = HttpStatusCode.TooManyRequests) =>
        Throttled(status, "soon");

    private static BooruCdnResponse Throttled(HttpStatusCode status, string? retryAfter) => new()
    {
        Status = status, ContentType = "text/html",
        Body = "<html><body>Too many requests.</body></html>"u8.ToArray(),
        Headers = retryAfter is null ? new Dictionary<string, string>() : new Dictionary<string, string> { ["Retry-After"] = retryAfter }
    };

    /// <summary>
    /// A 200 image whose body is <paramref name="length"/> bytes (valid PNG signature, then zeros), streamed without
    /// being held in memory. <paramref name="declareLength"/> false answers without Content-Length (chunked).
    /// </summary>
    internal static BooruCdnResponse Oversized(long length, bool declareLength = true, string contentType = "image/png") => new()
    {
        ContentType = contentType, GeneratedLength = length, DeclareLength = declareLength
    };

    /// <summary>A real image under a content type that is not an image.</summary>
    internal static BooruCdnResponse WrongContentType(byte[]? body = null, string contentType = "text/html") => new()
    {
        Body = body ?? BooruTinyImages.Png(), ContentType = contentType
    };

    /// <summary>A challenge page served as 200 and labelled as an image (signature check must refuse it).</summary>
    internal static BooruCdnResponse HtmlLabelledAsImage(string contentType = "image/jpeg") => new()
    {
        Body = BooruTinyImages.Html(), ContentType = contentType
    };

    /// <summary>The first <paramref name="keep"/> bytes of an image: a valid signature, a body no decoder accepts.</summary>
    internal static BooruCdnResponse Truncated(byte[]? full = null, int keep = 24, string contentType = "image/png")
    {
        byte[] source = full ?? BooruTinyImages.Png();
        return new() { Body = source.AsSpan(0, Math.Min(keep, source.Length)).ToArray(), ContentType = contentType };
    }

    /// <summary>A 200 with no bytes at all.</summary>
    internal static BooruCdnResponse EmptyBody(string contentType = "image/png") => new() { ContentType = contentType };

