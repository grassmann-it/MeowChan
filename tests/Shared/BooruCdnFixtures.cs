/// <summary>What the script saw of one request; the host must never send credentials or anything but GET.</summary>
internal sealed record BooruCdnRequest(Uri Url, string Method, bool HasAuthorization, bool HasCookie, string? Accept,
    string? AcceptEncoding, string? UserAgent);

/// <summary>
/// URL-keyed script of CDN answers with a request log and in-flight accounting. Not a transport by itself: wrap it in
/// <see cref="BooruCdnHandler"/> or call <see cref="TryRespondAsync"/> from a larger stub.
/// </summary>
internal sealed class BooruCdnScript
{
    private readonly object _gate = new();
    private readonly Dictionary<string, BooruCdnResponse> _rules = new(StringComparer.Ordinal);
    private int _inFlight;
    private int _maxInFlight;

    internal ConcurrentQueue<BooruCdnRequest> Requests { get; } = new();
    /// <summary>Requests the production code must never make: not GET, credentials, not https, foreign host, odd port.</summary>
    internal ConcurrentQueue<string> Violations { get; } = new();
    /// <summary>The only host the script answers; anything else is a violation and a transport error.</summary>
    internal string Host { get; init; } = "cdn.donmai.us";
    /// <summary>Answer for an address without a rule (404 by default, like a CDN path that does not exist).</summary>
    internal BooruCdnResponse Fallback { get; set; } = BooruCdn.Status(HttpStatusCode.NotFound);

    internal int InFlight => Volatile.Read(ref _inFlight);
    /// <summary>The highest number of requests that were being answered at the same moment.</summary>
    internal int MaxInFlight => Volatile.Read(ref _maxInFlight);

    /// <summary>Scripts one address (absolute https URL). A later call for the same address replaces the rule.</summary>
    internal BooruCdnScript On(string url, BooruCdnResponse response)
    {
        lock (_gate) _rules[new Uri(url).AbsoluteUri] = response;
        return this;
    }

    internal BooruCdnScript On(Uri url, BooruCdnResponse response) => On(url.AbsoluteUri, response);

    internal bool HasRule(Uri url) { lock (_gate) return _rules.ContainsKey(url.AbsoluteUri); }

    internal int Count(Uri url) => Requests.Count(request => request.Url == url);

    internal int Count(string pathPrefix) => Requests.Count(request => request.Url.AbsolutePath.StartsWith(pathPrefix, StringComparison.Ordinal));

    /// <summary>Answers the request from the rule for its address, or <see cref="Fallback"/>.</summary>
    internal async Task<HttpResponseMessage> RespondAsync(HttpRequestMessage request, CancellationToken cancellationToken)
    {
        Uri url = request.RequestUri ?? throw new InvalidOperationException("A CDN request needs an address.");
        Record(request, url);
        BooruCdnResponse rule;
        lock (_gate) rule = _rules.TryGetValue(url.AbsoluteUri, out BooruCdnResponse? found) ? found : Fallback;
        int now = Interlocked.Increment(ref _inFlight);
        int seen;
        while (now > (seen = Volatile.Read(ref _maxInFlight)) && Interlocked.CompareExchange(ref _maxInFlight, now, seen) != seen) { }
        try
        {
            await Task.Yield();
            if (rule.Gate is { } gate) await gate.Task.WaitAsync(cancellationToken).ConfigureAwait(false);
            cancellationToken.ThrowIfCancellationRequested();
            return Build(rule, request);
        }
        finally
        {
            Interlocked.Decrement(ref _inFlight);
        }
    }

    /// <summary>Like <see cref="RespondAsync"/>, but null when no rule exists for the address (the caller keeps its own behavior).</summary>
    internal Task<HttpResponseMessage>? TryRespondAsync(HttpRequestMessage request, CancellationToken cancellationToken) =>
        request.RequestUri is { } url && HasRule(url) ? RespondAsync(request, cancellationToken) : null;

    private void Record(HttpRequestMessage request, Uri url)
    {
        Requests.Enqueue(new BooruCdnRequest(url, request.Method.Method, request.Headers.Authorization is not null,
            request.Headers.Contains("Cookie") || request.Headers.Contains("Proxy-Authorization"),
            request.Headers.Accept.ToString(), request.Headers.AcceptEncoding.ToString(), request.Headers.UserAgent.ToString()));
        if (request.Method != HttpMethod.Get) Violations.Enqueue("method " + request.Method + " " + url);
        if (request.Headers.Authorization is not null) Violations.Enqueue("authorization " + url);
        if (request.Headers.Contains("Cookie")) Violations.Enqueue("cookie " + url);
        if (request.Headers.Contains("Proxy-Authorization")) Violations.Enqueue("proxy-authorization " + url);
        if (url.Scheme != Uri.UriSchemeHttps) Violations.Enqueue("scheme " + url);
        if (!url.IsDefaultPort || url.UserInfo.Length > 0) Violations.Enqueue("authority " + url);
        if (!string.Equals(url.Host, Host, StringComparison.OrdinalIgnoreCase))
        {
            Violations.Enqueue("host " + url);
            throw new HttpRequestException("The CDN script refused an unknown host: " + url.Host);
        }
    }

    private static HttpResponseMessage Build(BooruCdnResponse rule, HttpRequestMessage request)
    {
        HttpContent content = rule.GeneratedLength is { } length
            ? new StreamContent(new GeneratedStream(length, seekable: rule.DeclareLength))
            : new ByteArrayContent(rule.Body);
        // Content-Type may be deliberately odd; add it without validation.
        if (rule.ContentType is { } contentType) content.Headers.TryAddWithoutValidation("Content-Type", contentType);
        HttpResponseMessage response = new(rule.Status)
        {
            Content = content,
            RequestMessage = rule.AnsweredFrom is { } from ? new HttpRequestMessage(request.Method, from) : request
        };
        foreach (KeyValuePair<string, string> header in rule.Headers) response.Headers.TryAddWithoutValidation(header.Key, header.Value);
        return response;
    }

    /// <summary>PNG signature, then zeros up to <c>length</c>; read-only, optionally seekable so Content-Length is known.</summary>
    private sealed class GeneratedStream(long length, bool seekable) : Stream
    {
        private static readonly byte[] Signature = { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A };
        private long _position;

        public override bool CanRead => true;
        public override bool CanSeek => seekable;
        public override bool CanWrite => false;
        public override long Length => seekable ? length : throw new NotSupportedException();
        public override long Position
        {
            get => seekable ? _position : throw new NotSupportedException();
            set { if (!seekable) throw new NotSupportedException(); _position = Math.Clamp(value, 0, length); }
        }

        public override int Read(byte[] buffer, int offset, int count) => Read(buffer.AsSpan(offset, count));

        public override int Read(Span<byte> buffer)
        {
            int count = (int)Math.Min(buffer.Length, length - _position);
            for (int index = 0; index < count; index++)
            {
                long at = _position + index;
                buffer[index] = at < Signature.Length ? Signature[at] : (byte)0;
            }
            _position += count;
            return count;
        }

        public override ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default) =>
            ValueTask.FromResult(Read(buffer.Span));

        public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken) =>
            Task.FromResult(Read(buffer.AsSpan(offset, count)));

        public override long Seek(long offset, SeekOrigin origin)
        {
            if (!seekable) throw new NotSupportedException();
            Position = origin switch
            {
                SeekOrigin.Begin => offset, SeekOrigin.Current => _position + offset, _ => length + offset
            };
            return _position;
        }

        public override void Flush() { }
        public override void SetLength(long value) => throw new NotSupportedException();
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
    }
}

/// <summary>The script as a transport: hand it to <c>new HttpClient(handler)</c> or to the host code under test.</summary>
internal sealed class BooruCdnHandler : HttpMessageHandler
{
    internal BooruCdnHandler(BooruCdnScript? script = null) => Script = script ?? new BooruCdnScript();

    internal BooruCdnScript Script { get; }

    internal HttpClient Client() => new(this, disposeHandler: false) { Timeout = Timeout.InfiniteTimeSpan };

    protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken) =>
        Script.RespondAsync(request, cancellationToken);
}
